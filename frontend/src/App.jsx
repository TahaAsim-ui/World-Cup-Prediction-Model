import { useState, useEffect } from 'react'
import TeamSelector from './components/TeamSelector'
import PredictionCard from './components/PredictionCard'
import BracketPage from './pages/BracketPage'
import GroupStagePage from './pages/GroupStagePage'
import { WORLD_CUP_2026_TEAMS } from './utils/countryUtils'

export default function App() {
  const [page, setPage]             = useState('predictor')  // 'predictor' | 'groups' | 'bracket'
  const [teams, setTeams]           = useState([])
  const [teamsLoading, setTeamsLoading] = useState(true)
  const [team1, setTeam1]           = useState('')
  const [team2, setTeam2]           = useState('')
  const [prediction, setPrediction] = useState(null)
  const [loading, setLoading]       = useState(false)
  const [error, setError]           = useState('')
  const [modelInfo, setModelInfo]   = useState(null)

  useEffect(() => {
    fetch('/api/teams')
      .then(r => r.json())
      .then(d => {
        const wc = (d.teams || []).filter(t => WORLD_CUP_2026_TEAMS.has(t))
        setTeams(wc)
        setTeamsLoading(false)
      })
      .catch(() => setTeamsLoading(false))

    fetch('/api/model-info')
      .then(r => r.json())
      .then(setModelInfo)
      .catch(() => {})
  }, [])

  const canPredict = team1 && team2 && team1 !== team2 && !loading

  const handlePredict = async () => {
    if (!canPredict) return
    setLoading(true)
    setError('')
    setPrediction(null)
    try {
      const res = await fetch('/api/predict', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ team1, team2 }),
      })
      const data = await res.json()
      if (data.error) throw new Error(data.error)
      setPrediction(data)
    } catch (err) {
      setError(err.message || 'Failed to get prediction. Is the server running?')
    } finally {
      setLoading(false)
    }
  }

  const handleSwap = () => {
    setTeam1(team2)
    setTeam2(team1)
    setPrediction(null)
  }

  return (
    <div className="app">
      {/* Header */}
      <header className="header">
        <div className="header-inner">
          <div className="header-badge">⚽ AI Powered</div>
          <h1 className="header-title">World Cup AI Match Predictor</h1>
          <p className="header-subtitle">
            Select two 2026 World Cup nations to receive a probability-based match prediction
            generated by a machine learning model trained on{' '}
            {modelInfo ? `${modelInfo.training_matches} international matches` : 'historical international match data'}.
          </p>
        </div>
      </header>

      {/* Navigation tabs */}
      <nav className="nav-tabs">
        <button
          className={`nav-tab ${page === 'predictor' ? 'active' : ''}`}
          onClick={() => setPage('predictor')}
        >
          ⚡ Match Predictor
        </button>
        <button
          className={`nav-tab ${page === 'groups' ? 'active' : ''}`}
          onClick={() => setPage('groups')}
        >
          📋 Group Stage
        </button>
        <button
          className={`nav-tab ${page === 'bracket' ? 'active' : ''}`}
          onClick={() => setPage('bracket')}
        >
          🏆 Knockout Bracket
        </button>
      </nav>

      {/* ── Match Predictor page ── */}
      {page === 'predictor' && (
        <main className="main">
          <div className="selector-card">
            <div className="selectors-row">
              <TeamSelector
                label="Select Team 1"
                teams={teams}
                value={team1}
                onChange={v => { setTeam1(v); setPrediction(null) }}
                excludeTeam={team2}
              />
              <button
                className="swap-btn"
                onClick={handleSwap}
                title="Swap teams"
                disabled={!team1 && !team2}
              >
                ⇄
              </button>
              <TeamSelector
                label="Select Team 2"
                teams={teams}
                value={team2}
                onChange={v => { setTeam2(v); setPrediction(null) }}
                excludeTeam={team1}
              />
            </div>

            {teamsLoading && <p className="loading-teams">Loading teams…</p>}

            {team1 && team2 && team1 === team2 && (
              <p className="inline-error">Please select two different teams.</p>
            )}

            <button
              className={`predict-btn ${!canPredict ? 'predict-btn-disabled' : ''}`}
              onClick={handlePredict}
              disabled={!canPredict}
            >
              {loading ? (
                <span className="spinner-row">
                  <span className="spinner" /> Predicting…
                </span>
              ) : '⚡ Predict Match'}
            </button>
          </div>

          {error && <div className="error-banner">⚠ {error}</div>}

          {prediction && (
            <div className="result-wrapper">
              <PredictionCard data={prediction} />
            </div>
          )}

          {modelInfo && (
            <div className="model-info-card">
              <h3 className="model-info-title">Model Information</h3>
              <div className="model-info-grid">
                <div className="model-info-item">
                  <span className="model-info-label">Model Type</span>
                  <span className="model-info-value">{modelInfo.model_type}</span>
                </div>
                <div className="model-info-item">
                  <span className="model-info-label">Prediction Target</span>
                  <span className="model-info-value">{modelInfo.prediction_target}</span>
                </div>
                <div className="model-info-item">
                  <span className="model-info-label">Training Data</span>
                  <span className="model-info-value">{modelInfo.training_matches} matches ({modelInfo.data_range})</span>
                </div>
                <div className="model-info-item">
                  <span className="model-info-label">Features Used</span>
                  <span className="model-info-value">{modelInfo.features}</span>
                </div>
                <div className="model-info-item">
                  <span className="model-info-label">Test Accuracy</span>
                  <span className="model-info-value model-accuracy">{modelInfo.test_accuracy}</span>
                </div>
              </div>
            </div>
          )}
        </main>
      )}

      {/* ── Group stage page ── */}
      {page === 'groups' && <GroupStagePage />}

      {/* ── Bracket page ── */}
      {page === 'bracket' && <BracketPage />}

      <footer className="footer">
        Predictions are generated by a trained ML model and are probabilistic estimates, not guarantees.
      </footer>
    </div>
  )
}
